const normalize = (name) =>
  String(name ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]/g, '')
    .replace(/\s+/g, ' ')
    .trim()

/** Номера линий станции (может быть несколько у пересадочных). */
export function stationLineIds(name) {
  return STATION_LINES[normalize(name)] || []
}

/** Цвета линий станции. */
export function stationColors(name) {
  return stationLineIds(name).map((id) => METRO_LINES[id]?.color).filter(Boolean)
}

/** Основной цвет станции (для одной точки-индикатора). */
export function stationColor(name) {
  return stationColors(name)[0] || UNKNOWN_COLOR
}

/** Стиль точки: у пересадочных — двухцветный круг, иначе сплошной цвет ветки. */
export function stationDotStyle(name) {
  const colors = stationColors(name)
  if (colors.length > 1) {
    return { background: `conic-gradient(${colors[0]} 0 50%, ${colors[1]} 50% 100%)` }
  }
  return { background: colors[0] || UNKNOWN_COLOR }
}

/** Подпись для подсказки: «М5 Фрунзенско-Приморская». */
export function stationLineTitle(name) {
  const lines = stationLineIds(name)
  if (!lines.length) return 'Линия не определена'
  return lines.map((id) => `${METRO_LINES[id].short} · ${METRO_LINES[id].name}`).join(' / ')
}
